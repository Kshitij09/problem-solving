# 83. Majority Element-I
# https://takeuforward.org/practice/dsa/majority-element-i

# @code=begin
from itertools import islice
class Solution:
    def majorityElement(self, nums):
        leader = nums[0]
        leader_count = 1
        for num in islice(nums, 1, None):
            if num == leader:
                leader_count += 1
            else:
                leader_count -= 1

            if leader_count == 0:
                leader = num
                leader_count = 1

        return leader
# @code=end


