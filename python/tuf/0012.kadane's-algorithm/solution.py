# 12. Kadane's Algorithm
# https://takeuforward.org/practice/dsa/kadane's-algorithm

# @code=begin
class Solution:
    def maxSubArray(self, nums):
        sum = 0
        max_sum = float("-inf")
        for num in nums:
            sum += num
            max_sum = max(sum, max_sum)
            sum = max(0, sum)
        return max_sum
# @code=end


