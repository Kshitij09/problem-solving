"""pytest plugin that turns leetgo problem directories into tests.

For every `testcases.txt` next to a `solution.py` (as generated by `leetgo pick`), it collects:
  - `case<N>`: runs solution.py's `__main__` block on example N and compares the printed
    `output:` line with the expected output.
  - `submission`: runs every example again, but against only what LeetCode will receive (the code
    between `# @lc code=begin` and `# @lc code=end`) plus LeetCode's implicit prelude. It fails if
    the solution relies on imports or helpers defined outside the markers.

Comparison mirrors `leetgo test -L`: values are compared as JSON, floats within 1e-5, and
top-level lists ignore order when question.md says "return ... in any order". When that isn't
enough (e.g. nested lists in any order), add a `judge.py` next to solution.py defining
`judge(expected, actual) -> bool` over the JSON-decoded values.
"""

from __future__ import annotations

import contextlib
import io
import importlib.util
import json
import linecache
import math
import re
from dataclasses import dataclass
from pathlib import Path

import pytest

CODE_BEGIN = "# @lc code=begin"
CODE_END = "# @lc code=end"
OUTPUT_MARK = "output:"
ANY_ORDER_RE = re.compile(r"return.* in any order", re.IGNORECASE)

# What LeetCode's Python3 judge provides without explicit imports. Kept deliberately minimal:
# import anything else (collections, heapq, ...) inside the markers, as you would in an interview.
LEETCODE_PRELUDE = "from typing import *\nfrom leetgo_py import ListNode, TreeNode\n"
# The local I/O harness after `code=end` needs these; they are not visible to LeetCode.
HARNESS_IMPORTS = (
    "from leetgo_py import deserialize, serialize, split_array, join_array, read_line\n"
)


@dataclass(frozen=True)
class Case:
    number: int
    input: str
    output: str | None


def parse_testcases(text: str) -> list[Case]:
    cases = []
    for block in re.split(r"\n\s*\n", text.strip()):
        if not block.strip():
            continue
        _, _, rest = block.partition("input:")
        input_part, has_output, output_part = rest.partition(OUTPUT_MARK)
        output = output_part.strip() if has_output else ""
        cases.append(Case(len(cases) + 1, input_part.strip() + "\n", output or None))
    return cases


def submission_source(source: str, path: Path) -> str:
    begin, end = source.find(CODE_BEGIN), source.find(CODE_END)
    if begin == -1 or end == -1 or end < begin:
        raise pytest.fail.Exception(f"{path}: missing '{CODE_BEGIN}' / '{CODE_END}' markers")
    submitted = source[begin + len(CODE_BEGIN) : end]
    harness = source[end + len(CODE_END) :]
    return LEETCODE_PRELUDE + submitted + "\n" + HARNESS_IMPORTS + harness


def run_main(source: str, filename: str, stdin: str) -> str:
    """Executes `source` as __main__ with `stdin` and returns its last `output:` value."""
    # Register the source so tracebacks can show lines of the synthesized submission.
    linecache.cache[filename] = (len(source), None, source.splitlines(True), filename)
    code = compile(source, filename, "exec")
    out = io.StringIO()
    with (
        contextlib.redirect_stdout(out),
        pytest.MonkeyPatch.context() as mp,
    ):
        mp.setattr("sys.stdin", io.StringIO(stdin))
        exec(code, {"__name__": "__main__", "__file__": filename})
    printed = [line for line in out.getvalue().splitlines() if line.startswith(OUTPUT_MARK)]
    if not printed:
        raise AssertionError(f"no '{OUTPUT_MARK}' line printed; stdout was:\n{out.getvalue()}")
    return printed[-1][len(OUTPUT_MARK) :].strip()


def _parse(value: str):
    try:
        return json.loads(value)
    except json.JSONDecodeError:
        return value


def _equal(expected, actual) -> bool:
    if isinstance(expected, float) or isinstance(actual, float):
        if isinstance(expected, (int, float)) and isinstance(actual, (int, float)):
            return math.isclose(expected, actual, abs_tol=1e-5)
        return False
    if isinstance(expected, list) and isinstance(actual, list):
        return len(expected) == len(actual) and all(map(_equal, expected, actual))
    return expected == actual


def load_custom_judge(path: Path):
    if not path.exists():
        return None
    spec = importlib.util.spec_from_file_location(f"judge_{path.parent.name}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.judge


def outputs_match(expected: str, actual: str, ignore_order: bool, custom_judge=None) -> bool:
    exp, act = _parse(expected), _parse(actual)
    if custom_judge is not None:
        return bool(custom_judge(exp, act))
    if _equal(exp, act):
        return True
    if ignore_order and isinstance(exp, list) and isinstance(act, list):
        key = lambda v: json.dumps(v, sort_keys=True)
        return sorted(map(key, exp)) == sorted(map(key, act))
    return False


class LeetgoFile(pytest.File):
    def collect(self):
        solution = self.path.with_name("solution.py")
        question = self.path.with_name("question.md")
        ignore_order = question.exists() and bool(ANY_ORDER_RE.search(question.read_text()))
        cases = parse_testcases(self.path.read_text())
        for case in cases:
            yield CaseItem.from_parent(
                self, name=f"case{case.number}", solution=solution, cases=[case],
                ignore_order=ignore_order, submission=False,
            )
        yield CaseItem.from_parent(
            self, name="submission", solution=solution, cases=cases,
            ignore_order=ignore_order, submission=True,
        )


class CaseFailure(Exception):
    pass


class CaseItem(pytest.Item):
    def __init__(self, *, solution: Path, cases: list[Case], ignore_order: bool,
                 submission: bool, **kwargs):
        super().__init__(**kwargs)
        self.solution, self.cases = solution, cases
        self.ignore_order, self.submission = ignore_order, submission

    def runtest(self):
        source = self.solution.read_text()
        filename = str(self.solution)
        if self.submission:
            source = submission_source(source, self.solution)
            filename += " [submission]"
        runnable = [c for c in self.cases if c.output is not None]
        if not runnable:
            pytest.skip("no expected output")
        for case in runnable:
            actual = run_main(source, filename, case.input)
            custom_judge = load_custom_judge(self.solution.with_name("judge.py"))
            if not outputs_match(case.output, actual, self.ignore_order, custom_judge):
                raise CaseFailure(case, actual)

    def repr_failure(self, excinfo):
        if isinstance(excinfo.value, CaseFailure):
            case, actual = excinfo.value.args
            return (
                f"case {case.number} failed\n"
                f"  input:\n    {case.input.strip().replace(chr(10), chr(10) + '    ')}\n"
                f"  expected: {case.output}\n"
                f"  actual:   {actual}"
            )
        # Show only frames from the solution, not pytest or this plugin.
        frames = excinfo.traceback.filter(
            lambda entry: str(entry.path).startswith(str(self.solution))
        )
        if frames:
            excinfo.traceback = frames
        report = super().repr_failure(excinfo, style="short")
        if self.submission and isinstance(excinfo.value, NameError):
            report = (
                f"{report}\n\nOnly the code between the @lc markers is submitted. Move imports "
                "and helpers inside the markers."
            )
        return report

    def reportinfo(self):
        return self.solution, None, f"{self.parent.path.parent.name}::{self.name}"


def pytest_collect_file(file_path: Path, parent):
    if file_path.name == "testcases.txt" and file_path.with_name("solution.py").exists():
        return LeetgoFile.from_parent(parent, path=file_path)
    return None
